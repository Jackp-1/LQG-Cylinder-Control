fig = figure('Color','w', ...
             'Units','pixels', ...
             'Position',[50 50 1250 400], ...
             'Renderer','painters');

t = tiledlayout(fig, 1, 1, ...
    'TileSpacing','compact', ...
    'Padding','compact');
ax1 = nexttile(t);
idx_list = [8 11 15 18];
w = logspace(-5, 0, 30000);
ax = gca;
hold(ax, 'on');
grid(ax, 'on');
box(ax, 'on');


colororder([ ...
    0/255 0/255 0/255;    ...
    230/255 20/255   0/255;    ...
    0/255   200/255   0/255;    ...
    20/255 0 200/255;    ...
    100/255 100/255 0/255;     ...
    0/255 150/255 150/255;     ...
    ]);


[~, ~, wout] = bode(H3_lqgi{idx_list(1)}, w);
St = wout(:) / (U_inf * 2*pi);

for k = 1:numel(idx_list)
    i = idx_list(k);

    [mag, ~, ~] = bode(H3_lqgi{i}, w);
    mag = squeeze(mag);
    magdb = mag2db(mag);

    plot(ax, St, magdb, ...
        'DisplayName', "Rank " + num2str(i), ...
        'LineWidth', 1.5);
end


xlabel(ax, 'Strouhal number, $St$', ...
    'Interpreter', 'latex', ...
    'FontSize', 16);

ylabel(ax, 'Sensitivity, $|S(e^{j\varphi})|$ (dB)', ...
    'Interpreter', 'latex', ...
    'FontSize', 16);

legend(ax, 'show', ...
    'FontSize', 12, ...
    'Location', 'northwest');

x_zoom = [0.01 1.5];
y_zoom = [-5 5];

rectangle(ax, ...
    'Position', [x_zoom(1), y_zoom(1), diff(x_zoom), diff(y_zoom)], ...
    'LineStyle', '--', ...
    'EdgeColor', 'k', ...
    'LineWidth', 1.2);

xlim(ax, [1e-4 2]);
ylim(ax, [-40 8]);

ax2 = axes('Position', [0.4 0.22 0.25 0.3]);
hold(ax2, 'on');
grid(ax2, 'on');
box(ax2, 'on');

colororder(ax2, colororder(ax));

Lv = (St >= x_zoom(1)) & (St <= x_zoom(2));

for k = 1:numel(idx_list)
    i = idx_list(k);

    [mag, ~, ~] = bode(H3_lqgi{i}, w);
    mag = squeeze(mag);
    magdb = mag2db(mag);

    plot(ax2, St(Lv), magdb(Lv), ...
        'LineWidth', 1.5, ...
        'DisplayName', num2str(i));
end

xlim(ax2, x_zoom);
ylim(ax2, y_zoom);

ax2.XTick = [];
ax2.YTick = [-3 0];
ax2.YTickLabel = {'-3 dB', ''};
ax2.FontSize = 12;

axs = findall(gcf,'Type','axes');
set(axs, ...
    'FontName',      'Times New Roman', ...
    'FontSize',      18, ...
    'LineWidth',     1, ...
    'TickDir',       'in', ...
    'TickLabelInterpreter', 'latex', ...
    'XMinorTick',    'on', ...
    'YMinorTick',    'on', ...
    'XScale', 'log', ...
    'Layer',         'bottom');

exportgraphics(gcf,"figures\Fig8.pdf","ContentType","vector")