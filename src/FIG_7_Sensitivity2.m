fig = figure('Color','w', ...
             'Units','pixels', ...
             'Position',[50 50 1250 400], ...
             'Renderer','painters');
t = tiledlayout(fig, 1, 1, ...
    'TileSpacing','compact', ...
    'Padding','compact');
ax1 = nexttile(t);
omega = logspace(-4, 3, 30000);
plantIndex      = 11;
controllerIndex = [5, 11];
curveLabels = {
    '$c=5,\ r=11$'
    '$c=11,\ r=11$'
};
plantData = sys{plantIndex};

Dplant = zeros( ...
    size(plantData.C, 1), ...
    size(plantData.B, 2));

G = ss( ...
    plantData.A, ...
    plantData.B, ...
    plantData.C, ...
    Dplant, ...
    Ts);


ax = gca;
hold(ax, 'on');
grid(ax, 'on');
box(ax, 'on');


for k = 1:numel(controllerIndex)

    controller = C_lqgi{controllerIndex(k)};
    loopTransfer = G * controller;

    sensitivity = feedback(1, loopTransfer);

    magnitude = bode(sensitivity, omega);
    magnitude = squeeze(magnitude);

    magnitudeDb = mag2db(magnitude);

    strouhal = omega ./ (2*pi*U_inf);

    plot( ...
        ax, ...
        strouhal, ...
        magnitudeDb, ...
        'LineWidth', 1.8, ...
        'DisplayName', curveLabels{k});
end
xlim(ax, [0.05, 0.5]);
ylim([-40 15])
xlabel( ...
    ax, ...
    'Strouhal number, $St$', ...
    'Interpreter', 'latex');

ylabel( ...
    ax, ...
    'Sensitivity, $|S(\mathrm{e}^{\mathrm{j}\varphi})|$ (dB)', ...
    'Interpreter', 'latex');

legend( ...
    ax, ...
    'Location',    'northwest', ...
    'Interpreter', 'latex', ...
    'FontSize',    14, ...
    'Box',         'on');

colororder([ ...
    0/255 0/255 0/255;    ...
