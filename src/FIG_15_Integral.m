ref = [zeros(8000,1); 0.088*ones(31350,1); -0.26*ones(29999,1)];

cl_raw = [Base_lift(1:8000,2); Ref_Tracking(:,13)] / q;
cd_raw = [Base_drag(1:8000,2); Ref_Tracking(:,end)] / q;
cm_raw = [zeros(8000,1); Ref_Tracking(:,end-1)] / U_inf;

tau = Tau(1:numel(cl_raw));

mov1 = movmean(Base_lift(1:8000,2)/q, 775);
mov2 = movmean(Ref_Tracking(1:39300,13)/q, 831);
mov3 = movmean(Ref_Tracking(39301:end,13)/q, 770);
mov  = [mov1; mov2; mov3];

fig = figure('Color','w', ...
             'Units','pixels', ...
             'Position',[50 50 1250 600], ...
             'Renderer','painters');

t = tiledlayout(fig, 3, 1, ...
    'TileSpacing','compact', ...
    'Padding','compact');


fs  = 16;
lw  = 1.6;
clr1 = [0 0 0];
clr2 = [230/255 20/255   0/255];
clr3 = [0/255   200/255   0/255];

ax1 = nexttile(t);
hold(ax1, 'on');
plot(ax1, tau, cl_raw, 'Color', clr1, 'LineWidth', lw);
plot(ax1, tau, ref,    'Color', clr2, 'LineWidth', lw);
plot(ax1, tau, mov,    'Color', clr3, 'LineStyle', '-.', 'LineWidth', lw);

xlim(ax1, [0 80]);
ylim(ax1, [-1.2 1.2]);
ylabel(ax1, '$C_l$', 'Interpreter','latex', 'FontSize', fs);
legend(ax1, {'$C_l$','$C_{l,\mathrm{ref}}$','$\tilde{C}_l$'}, ...
    'Interpreter','latex', ...
    'FontSize', 12, ...
    'Location','northeast', ...
    'Box','on');
grid(ax1, 'on');
box(ax1, 'off');

ax2 = nexttile(t);
hold(ax2, 'on');
plot(ax2, tau, cd_raw, 'Color', clr1, 'LineWidth', lw);
plot(tau,ones(1,69349)*Min_drag/q,'k-.','LineWidth',1.5)
plot(tau,ones(1,69349)*Mean_Base_Drag/q,'r-.','LineWidth',1.5)

xlim(ax2, [0 80]);
ylim(ax2, [0.6 1.4])
ylabel(ax2, '$C_d$', 'Interpreter','latex', 'FontSize', fs);
grid(ax2, 'on');
box(ax2, 'off');
text(ax2, ...
    0.15, 0.97,'$\bar{C}_{d,base}$', ...
    'Units','normalized', ...
    'FontName','Times New Roman', ...
    'FontSize',18, ...
    'Color', [1,0,0], ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','top')

text(ax2, ...
    0.03, 0.44, '$\bar{C}_{d,min}$', ...
    'Units','normalized', ...
    'FontName','Times New Roman', ...
    'FontSize',18, ...
    'Color', [0,0,0], ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','top')

ax3 = nexttile(t);
hold(ax3, 'on');
plot(ax3, tau, cm_raw, 'Color', clr1, 'LineWidth', lw);

xlim(ax3, [0 80]);
ylim(ax3, [-1.4 1.4]);
ylabel(ax3, '$u_c/U_\infty$', 'Interpreter','latex', 'FontSize', fs);
xlabel(ax3, '$\tau$', 'Interpreter','latex', 'FontSize', fs);
grid(ax3, 'on');
box(ax3, 'off');


axs = [ax1 ax2 ax3];

set(axs, ...
    'FontName',      'Times New Roman', ...
    'FontSize',      18, ...
    'LineWidth',     1, ...
    'TickDir',       'in', ...
    'TickLabelInterpreter', 'latex', ...
    'XMinorTick',    'on', ...
    'YMinorTick',    'on', ...
    'XScale',        'linear', ...
    'Layer',         'top');

ax1.XTickLabel = [];
